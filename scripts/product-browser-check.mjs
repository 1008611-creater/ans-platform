// Read-only browser checks. No fixtures, sign-ins, model calls or database writes.
import puppeteer from "puppeteer";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import assert from "node:assert/strict";

const base = process.env.PRODUCT_PREVIEW_URL || "http://127.0.0.1:3107";
assert(["127.0.0.1", "localhost"].includes(new URL(base).hostname), "Use a local preview server");
const output = ".workbuddy/evidence/product-rebuild";
mkdirSync(output, { recursive: true });
const require = createRequire(import.meta.url);
const axe = readFileSync(require.resolve("axe-core/axe.min.js"), "utf8");
const browser = await puppeteer.launch({ executablePath: process.env.PUPPETEER_EXECUTABLE_PATH || "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
const report = { checks: [], accessibility: [], pageErrorCount: 0, translationErrorCount: 0 };
try {
  const page = await browser.newPage();
  page.on("pageerror", () => { report.pageErrorCount += 1; });
  page.on("console", (message) => { if (message.text().includes("Missing translation:")) report.translationErrorCount += 1; });
  async function visit(path, title, filename, viewport = { width: 1440, height: 1000 }) {
    await page.setViewport(viewport);
    const response = await page.goto(`${base}${path}`, { waitUntil: "networkidle0", timeout: 90_000 });
    assert.equal(response.status(), 200, path);
    const heading = await page.$eval("h1", (node) => node.textContent);
    assert(heading.includes(title), `Unexpected heading on ${path}`);
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
    assert.equal(overflow, false, `Horizontal overflow on ${path}`);
    const activeDesktopLinks = await page.$$eval('header nav a[aria-current="page"]', (nodes) => nodes.map((node) => node.getAttribute("href")));
    const expectedActive = path === "/" || path.startsWith("/explore") ? "/explore" : path.startsWith("/workflows") ? "/workflows" : undefined;
    if (expectedActive) assert.deepEqual(activeDesktopLinks, [expectedActive], `Incorrect active navigation on ${path}`);
    await page.screenshot({ path: `${output}/${filename}.png`, fullPage: true });
    await page.addScriptTag({ content: axe });
    const violations = await page.evaluate(async () => (await window.axe.run(document, { runOnly: { type: "tag", values: ["wcag2a", "wcag2aa", "wcag21aa"] } })).violations.map(({ id, impact, nodes }) => ({ id, impact, targets: nodes.map((node) => node.target) })));
    report.accessibility.push({ path, viewport: viewport.width, violations });
    report.checks.push({ path, viewport: viewport.width, status: response.status(), overflow });
  }
  await visit("/", "你的下一个作品", "home-desktop");
  await visit("/explore", "发现，值得你开工的项目", "explore-desktop");
  assert.equal((await page.$$(".ans-project-card")).length, 11);
  await visit("/explore?category=career&subcategory=resume", "发现", "career-filter");
  assert.equal((await page.$$(".ans-project-card")).length, 2);
  await visit("/explore?category=career&source=github&readiness=reference", "发现", "source-readiness-filter");
  assert.equal((await page.$$(".ans-project-card")).length, 1);
  assert(await page.$('a[href="/explore/open-resume"]'));
  const searchFilters = await page.$$eval('form[action="/explore"] input[type="hidden"]', (nodes) => Object.fromEntries(nodes.map((node) => [node.name, node.value])));
  assert.deepEqual(searchFilters, { category: "career", source: "github", readiness: "reference" });
  await visit("/explore?q=no-such-project", "发现", "search-empty");
  assert(await page.$(".ans-empty"));
  await visit("/explore/resume-story", "把你的项目", "detail-desktop");
  await page.click('[data-testid="generation-template"] summary');
  const template = await page.$eval('[data-testid="generation-template"] pre', (node) => node.textContent);
  assert(template.includes("目标工作流：简历项目条目（resume-bullets）"));
  assert(template.includes("[你的项目名称]"));
  assert(template.includes('"confirmation": "unconfirmed"'));
  assert.equal((template.match(/"key":/g) || []).length, 5);
  const startLink = await page.$eval('a[href*="workflow=resume-bullets"]', (node) => node.getAttribute("href"));
  assert(startLink.includes("goal=career"));
  await page.goto(`${base}${startLink}`, { waitUntil: "networkidle0" });
  const login = new URL(page.url());
  assert.equal(login.pathname, "/login");
  assert.equal(login.searchParams.get("callbackUrl"), "/projects?goal=career&workflow=resume-bullets#new-project");
  report.checks.push({ name: "selection-preserved-through-login", passed: true });
  await visit("/explore/remotion-video", "Remotion", "reference-detail");
  assert.equal(await page.$('a[href*="workflow="]'), null);
  assert.equal(await page.$('[data-testid="generation-template"]'), null);
  assert(await page.$('a[href="https://github.com/remotion-dev/remotion/blob/main/LICENSE.md"]'));
  assert((await page.$eval("main", (node) => node.textContent)).includes("自定义许可"));
  await visit("/workflows", "少一点重复", "workflows-desktop");
  assert.equal((await page.$$(".ans-flow-card")).length >= 7, true, "Official workflows unavailable");
  const communityState = await page.$eval("main", (node) => node.textContent);
  assert(communityState.includes("社区工作流暂时连接不上") || communityState.includes("暂时没有匹配的社区工作流") || await page.$('a[href^="/workflows/"]:not([href="/workflows/toonflow"]):not([href="/workflows/mine"]):not([href="/workflows/runs"]):not([href="/workflows/new"])'));
  report.checks.push({ name: "official-workflows-independent-from-community-state", passed: true });
  await visit("/workflows/toonflow", "Toonflow", "toonflow-desktop");
  assert.equal(await page.$eval('a[target="_blank"]', (node) => node.rel.includes("noopener")), true);
  const mobile = { width: 390, height: 844, deviceScaleFactor: 1, isMobile: true, hasTouch: true };
  await visit("/", "你的下一个作品", "home-mobile", mobile);
  await page.click(".ans-dino-trigger");
  await page.waitForSelector('[data-slot="popover-content"]');
  await page.screenshot({ path: `${output}/dino-mobile.png`, fullPage: false });
  const popoverFits = await page.$eval('[data-slot="popover-content"]', (node) => { const rect = node.getBoundingClientRect(); return rect.left >= 0 && rect.right <= innerWidth && rect.top >= 0 && rect.bottom < innerHeight - 60; });
  assert(popoverFits, "Dino popover overlaps mobile bottom navigation");
  await page.keyboard.press("Escape");
  await page.waitForSelector('[data-slot="popover-content"]', { hidden: true });
  assert.equal(await page.$('[data-slot="popover-content"]'), null);
  assert.equal(await page.$eval(".ans-dino-trigger", (node) => node.getAttribute("aria-expanded")), "false");
  await page.click(".ans-dino-trigger");
  await page.waitForSelector('[data-slot="popover-content"]');
  await page.click('[data-slot="popover-content"] a[href="/explore/resume-story"]');
  await page.waitForFunction(() => location.pathname === "/explore/resume-story" && !document.querySelector('[data-slot="popover-content"]'));
  report.checks.push({ name: "dino-keyboard-dismiss-and-mobile-placement", passed: true });
  await visit("/explore", "发现", "explore-mobile", mobile);
  await visit("/explore/resume-story", "把你的项目", "detail-mobile", mobile);
  await page.click('[data-testid="generation-template"] summary');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, "Template causes mobile overflow");
  await visit("/workflows", "少一点重复", "workflows-mobile", mobile);
  await page.emulateMediaFeatures([{ name: "prefers-reduced-motion", value: "reduce" }]);
  await page.click(".ans-dino-trigger");
  assert.equal(await page.$eval(".ans-dino-trigger", (node) => getComputedStyle(node).animationName), "none");
  report.checks.push({ name: "reduced-motion", passed: true });
  assert.equal(report.pageErrorCount, 0, "Browser runtime errors");
  assert.equal(report.translationErrorCount, 0, "Missing translations");
  const blockers = report.accessibility.flatMap((item) => item.violations.filter((violation) => ["critical", "serious"].includes(violation.impact)));
  console.log(JSON.stringify({ checks: report.checks.length, accessibilityBlockers: blockers.length, pageErrorCount: report.pageErrorCount, translationErrorCount: report.translationErrorCount }));
  assert.equal(blockers.length, 0, "Blocking accessibility findings; see browser-check.json");
} finally {
  writeFileSync(`${output}/browser-check.json`, JSON.stringify(report, null, 2));
  await browser.close();
}
